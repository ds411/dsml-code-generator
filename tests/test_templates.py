"""Tests of the template engine and its fixed settings (story #37).

The golden file `tests/golden/templates/service_gen.py` is the output of the
template `tests/templates/example/service_gen.py.j2`. CI runs `ruff format
--check` on the golden files (PRD-CORE-035).
"""

import os
import time
from pathlib import Path

import pytest

from dsml.generate.templates import TemplateEngine, TemplateEngineError, sort_values

ROOT = Path(__file__).resolve().parent.parent
TEMPLATES = ROOT / "tests" / "templates"
GOLDEN = ROOT / "tests" / "golden" / "templates" / "service_gen.py"


class Operation:
    def __init__(self, name: str) -> None:
        self.name = name


EXAMPLE_DATA = {
    "file_type": "python",
    "elements": ["OrderService::Order", "OrderService", "OrderService::CancelOrder"],
    "service": "order_service",
    "operations": [Operation("PlaceOrder"), Operation("CancelOrder"), Operation("class")],
    "entities": ["Order", "Customer", "Order", "customer"],
}


def _engine(tmp_path: Path, templates: dict[str, str | bytes]) -> TemplateEngine:
    for name, text in templates.items():
        path = tmp_path / name
        path.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(text, str):
            path.write_text(text, encoding="utf-8", newline="")
        else:
            path.write_bytes(text)
    return TemplateEngine.for_folder(tmp_path)


def test_golden_example() -> None:
    engine = TemplateEngine.for_folder(TEMPLATES)
    output = engine.render_bytes("example/service_gen.py.j2", EXAMPLE_DATA)
    assert output == GOLDEN.read_bytes(), (
        "The output is different from the golden file. If the change is correct, "
        "write the new output to tests/golden/templates/service_gen.py."
    )


def test_output_does_not_depend_on_the_order_of_the_data() -> None:
    engine = TemplateEngine.for_folder(TEMPLATES)
    reverse = {
        **EXAMPLE_DATA,
        "elements": list(reversed(EXAMPLE_DATA["elements"])),
        "operations": list(reversed(EXAMPLE_DATA["operations"])),
        "entities": list(reversed(EXAMPLE_DATA["entities"])),
    }
    assert engine.render("example/service_gen.py.j2", reverse) == GOLDEN.read_text("utf-8")


def test_package_header_template() -> None:
    engine = TemplateEngine()
    data = {"file_type": "typescript", "elements": ["b", "a"]}
    assert engine.render("common/header.j2", data) == (
        "// Generated by dsml 0. Do not edit.\n// Elements: a, b\n"
    )


def test_header_include_for_a_file_type_with_no_comments(tmp_path: Path) -> None:
    engine = _engine(tmp_path, {"a.json.j2": '{% include "common/header.j2" %}\n{"a": 1}\n'})
    assert engine.render("a.json.j2", {"file_type": "json", "elements": ["a"]}) == '{"a": 1}\n'


def test_undefined_value_gives_an_error(tmp_path: Path) -> None:
    engine = _engine(tmp_path, {"a.j2": "{{ missing }}\n"})
    with pytest.raises(TemplateEngineError, match="'missing' is undefined"):
        engine.render("a.j2", {})


def test_undefined_attribute_gives_an_error(tmp_path: Path) -> None:
    engine = _engine(tmp_path, {"a.j2": "{{ item.missing }}\n"})
    with pytest.raises(TemplateEngineError, match="has no attribute 'missing'"):
        engine.render("a.j2", {"item": Operation("a")})


def test_undefined_value_in_a_loop_gives_an_error(tmp_path: Path) -> None:
    engine = _engine(tmp_path, {"a.j2": "{% for x in missing %}{{ x }}{% endfor %}\n"})
    with pytest.raises(TemplateEngineError, match="'missing' is undefined"):
        engine.render("a.j2", {})


def test_none_gives_an_error(tmp_path: Path) -> None:
    engine = _engine(tmp_path, {"a.j2": "{{ value }}\n"})
    with pytest.raises(TemplateEngineError, match="must not write the value None"):
        engine.render("a.j2", {"value": None})


def test_lf_line_ends(tmp_path: Path) -> None:
    engine = _engine(tmp_path, {"a.j2": "a\r\nb\rc\n"})
    assert engine.render_bytes("a.j2", {}) == b"a\nb\nc\n"


def test_one_lf_at_the_end(tmp_path: Path) -> None:
    engine = _engine(tmp_path, {"a.j2": "a\n\n\n", "b.j2": "b"})
    assert engine.render("a.j2", {}) == "a\n"
    assert engine.render("b.j2", {}) == "b\n"


def test_cr_in_data_gives_an_error(tmp_path: Path) -> None:
    engine = _engine(tmp_path, {"a.j2": "{{ value }}\n"})
    with pytest.raises(TemplateEngineError, match="must not contain CR"):
        engine.render("a.j2", {"value": "a\r\nb"})


def test_utf8_with_no_byte_order_mark(tmp_path: Path) -> None:
    engine = _engine(tmp_path, {"a.j2": "Größe {{ value }}\n"})
    assert engine.render_bytes("a.j2", {"value": "€"}) == "Größe €\n".encode()


def test_fixed_whitespace_control(tmp_path: Path) -> None:
    template = "start\n    {% for x in items %}\n  - {{ x }}\n    {% endfor %}\nend\n"
    engine = _engine(tmp_path, {"a.j2": template})
    assert engine.render("a.j2", {"items": ["a", "b"]}) == "start\n  - a\n  - b\nend\n"


def test_no_autoescape(tmp_path: Path) -> None:
    engine = _engine(tmp_path, {"a.j2": "{{ value }}\n"})
    assert engine.render("a.j2", {"value": "<a & 'b'>"}) == "<a & 'b'>\n"


@pytest.mark.parametrize(
    "template",
    [
        "{{ lipsum() }}",
        "{{ [1, 2] | random }}",
        "{{ now() }}",
        "{{ environ }}",
        "{{ range.__globals__ }}",
    ],
)
def test_no_random_values_clock_or_environment(tmp_path: Path, template: str) -> None:
    engine = _engine(tmp_path, {"a.j2": template})
    with pytest.raises(TemplateEngineError):
        engine.render("a.j2", {})


def test_sandbox_blocks_access_to_python_internals(tmp_path: Path) -> None:
    engine = _engine(tmp_path, {"a.j2": "{{ ''.__class__.__mro__[1].__subclasses__() }}"})
    with pytest.raises(TemplateEngineError):
        engine.render("a.j2", {})


def test_sandbox_blocks_changes_to_the_data(tmp_path: Path) -> None:
    engine = _engine(tmp_path, {"a.j2": "{{ items.append(1) }}"})
    with pytest.raises(TemplateEngineError):
        engine.render("a.j2", {"items": []})


def test_output_does_not_change_with_the_clock_or_the_environment(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    engine = _engine(tmp_path, {"a.j2": '{{ header("python", ["a"]) }}x\n'})
    first = engine.render("a.j2", {})
    monkeypatch.setenv("TZ", "Pacific/Kiritimati")
    monkeypatch.setenv("USER", "other")
    time.tzset()
    try:
        assert engine.render("a.j2", {}) == first
    finally:
        monkeypatch.undo()
        time.tzset()


@pytest.mark.parametrize("name", ["../outside.j2", "/etc/hosts", "sub/../../outside.j2"])
def test_no_access_outside_the_template_folder(tmp_path: Path, name: str) -> None:
    (tmp_path / "outside.j2").write_text("secret\n", encoding="utf-8")
    folder = tmp_path / "templates"
    engine = _engine(folder, {"sub/a.j2": "a\n"})
    with pytest.raises(TemplateEngineError):
        engine.render(name, {})


def test_include_outside_the_template_folder_gives_an_error(tmp_path: Path) -> None:
    (tmp_path / "outside.j2").write_text("secret\n", encoding="utf-8")
    engine = _engine(tmp_path / "templates", {"a.j2": '{% include "../outside.j2" %}\n'})
    with pytest.raises(TemplateEngineError):
        engine.render("a.j2", {})


@pytest.mark.skipif(not hasattr(os, "symlink"), reason="The platform has no symbolic links.")
def test_no_symbolic_link_out_of_the_template_folder(tmp_path: Path) -> None:
    outside = tmp_path / "outside"
    outside.mkdir()
    (outside / "secret.j2").write_text("secret\n", encoding="utf-8")
    folder = tmp_path / "templates"
    folder.mkdir()
    (folder / "link").symlink_to(outside, target_is_directory=True)
    engine = TemplateEngine.for_folder(folder)
    with pytest.raises(TemplateEngineError):
        engine.render("link/secret.j2", {})


def test_sorted_filter() -> None:
    assert sort_values(["b", "B", "a", "A"]) == ["A", "B", "a", "b"]
    assert sort_values(["b", "a", "b"], unique=True) == ["a", "b"]
    operations = [Operation("b"), Operation("a")]
    assert [item.name for item in sort_values(operations, "name")] == ["a", "b"]


def test_name_filters(tmp_path: Path) -> None:
    template = (
        "{{ n | snake_case }} {{ n | kebab_case }} {{ n | pascal_case }} "
        "{{ n | camel_case }} {{ 'class' | python_name }}\n"
    )
    engine = _engine(tmp_path, {"a.j2": template})
    assert engine.render("a.j2", {"n": "CancelOrder"}) == (
        "cancel_order cancel-order CancelOrder cancelOrder class_\n"
    )


def test_name_that_is_not_correct_gives_an_error(tmp_path: Path) -> None:
    engine = _engine(tmp_path, {"a.j2": "{{ n | snake_case }}\n"})
    with pytest.raises(TemplateEngineError, match="must not start with a digit"):
        engine.render("a.j2", {"n": "1st"})
