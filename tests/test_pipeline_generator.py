# trace: PRD-TRACE-006
def test_each_job_is_a_symbol_of_its_elements(ir: Ir) -> None:
    files = PipelineGenerator(version="0.1.0").generate(ir, CONFIGURATION, None)
    symbols = {symbol.name: symbol for symbol in files[0].symbols}
    assert tuple(symbols) == JOBS
    for symbol in symbols.values():
        assert symbol.kind is SymbolKind.JOB
    for job in ("validate", "generate-check", "check-output"):
        assert symbols[job].elements == ("OrderService",)
    assert symbols["test-order-api"].elements == ("OrderService::orderApi",)
    assert symbols["plan-dev"].elements == ("OrderService::dev",)
    lines = files[0].content.decode("utf-8").split("\n")
    for symbol in symbols.values():
        assert lines[symbol.first_line - 1] == f"  {symbol.name}:"
        assert lines[symbol.last_line - 1].startswith("    ")


def test_job_symbols_stop_before_comments_blank_lines_and_top_level_keys() -> None:
    text = "on: push\njobs:\n  a:\n    x: 1\n\n  # B\n  b:\n    y: 2\n\nend: 1\n"
    symbols = job_symbols(text, lambda job: (job.upper(),))
    assert [(s.name, s.first_line, s.last_line, s.elements) for s in symbols] == [
        ("a", 3, 4, ("A",)),
        ("b", 7, 8, ("B",)),
    ]
    assert job_symbols("on: push\n", lambda job: ("x",)) == ()
    assert job_symbols(text, lambda job: ()) == ()


