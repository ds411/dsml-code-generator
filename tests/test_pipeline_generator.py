def _load_script() -> Any:
    spec = importlib.util.spec_from_file_location(
        "write_golden_pipelines", ROOT / "scripts/write_golden_pipelines.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


write_golden: Any = _load_script()


@pytest.fixture(scope="module")
def ir() -> Ir:
    return make_ir([EXAMPLE], ROOT)


def _workflow(ir: Ir, configuration: Configuration = CONFIGURATION) -> str:
    files = PipelineGenerator(version="0.1.0").generate(ir, configuration, None)
    assert files[0].path == PR_PATH
    return files[0].content.decode("utf-8")


def _jobs(text: str) -> dict[str, str]:
    """Give the text of each job, by job ID."""
    lines = text.split("\n")
    symbols = job_symbols(text, lambda job: ("x",))
    return {
        symbol.name: "\n".join(lines[symbol.first_line - 1 : symbol.last_line])
        for symbol in symbols
    }


def _read_tree(folder: Path) -> dict[str, bytes]:
    return {
        path.relative_to(folder).as_posix(): path.read_bytes()
        for path in sorted(folder.rglob("*"))
        if path.is_file()
    }


