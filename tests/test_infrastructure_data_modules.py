# trace: PRD-IAC-019, PRD-DSML-033
def test_a_new_role_value_gives_a_new_group(ir: Ir) -> None:
    def add_role(item: Element) -> Element:
        if item.kind != "Roles":
            return item
        literals = ListValue(
            items=(
                EnumValue(enumeration="OrderService::AppRoles", literal="clerk"),
                EnumValue(enumeration="OrderService::AppRoles", literal="admin"),
                EnumValue(enumeration="OrderService::AppRoles", literal="auditor"),
            )
        )
        return dataclasses.replace(item, attributes=(Attribute("literals", literals),))

    changed = dataclasses.replace(ir, elements=tuple(add_role(item) for item in ir.elements))
    call = _module_block(_text(_generate(changed), "envs/dev/main.gen.tf"), "users")
    assert '  groups        = ["admin", "auditor", "clerk"]\n' in call


