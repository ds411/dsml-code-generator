ROOT = Path(__file__).resolve().parent.parent
EXAMPLE = ROOT / "docs" / "model" / "examples" / "order-service.sysml"
ENVIRONMENTS = ("dev", "prod", "staging")
INFRA = PurePosixPath("infra")
DATABASE_ELEMENTS = "OrderService::orderDb, OrderService::orderDbAws"
USER_DIRECTORY_ELEMENTS = "OrderService::users, OrderService::usersAws"


@pytest.fixture(scope="module")
def ir() -> Ir:
    return make_ir([EXAMPLE], ROOT)


def _generate(ir: Ir) -> dict[str, OutputFile]:
    files = InfrastructureGenerator().generate(ir, Configuration(infrastructure=INFRA), None)
    return {file.path: file for file in files}


def _text(files: dict[str, OutputFile], path: str) -> str:
    return files[f"infra/{path}"].content.decode("utf-8")


def _module_block(text: str, address: str) -> str:
    start = text.index(f'module "{address}" {{\n')
    return text[start : text.index("\n}\n", start) + 3]


def _resource_block(text: str, address: str) -> str:
    resource_type, name = address.split(".")
    start = text.index(f'resource "{resource_type}" "{name}" {{\n')
    return text[start : text.index("\n}\n", start) + 3]


def _without(ir: Ir, *identities: str) -> Ir:
    """Give the IR with no elements and no links of the identities."""
    gone = set(identities)
    return dataclasses.replace(
        ir,
        elements=tuple(item for item in ir.elements if item.identity not in gone),
        links=tuple(
            link for link in ir.links if link.source not in gone and link.target not in gone
        ),
    )


# trace: PRD-IAC-001, PRD-IAC-002, PRD-TRACE-005
def test_generator_writes_the_files_of_the_two_modules(ir: Ir) -> None:
    files = _generate(ir)
    modules = sorted(path for path in files if path.startswith("infra/modules/"))
    assert modules == [
        f"infra/modules/{module}/{name}.gen.tf"
        for module in ("relational-database", "user-directory")
        for name in MODULE_FILES
    ]
    for path in modules:
        assert files[path].kind is Kind.GENERATED
        assert files[path].part == INFRASTRUCTURE
        elements = DATABASE_ELEMENTS if "relational-database" in path else USER_DIRECTORY_ELEMENTS
        assert _text(files, path.removeprefix("infra/")).startswith(
            f"# Generated by dsml 0. Do not edit.\n# Elements: {elements}\n\n"
        )


