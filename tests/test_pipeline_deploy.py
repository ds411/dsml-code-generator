def test_each_job_is_a_symbol_of_its_elements(ir: Ir) -> None:
    files = PipelineGenerator(version="0.1.0").generate(ir, CONFIGURATION, None)
    by_path = {file.path: file for file in files}
    expected = {
        MAIN_PATH: {
            "build-order-api": ("OrderService::orderApi",),
            "deploy-dev": ("OrderService::dev",),
        },
        PROMOTE_PATH: {
            "find-build": ("OrderService::orderApi",),
            "deploy-staging": ("OrderService::staging",),
            "deploy-prod": ("OrderService::prod",),
        },
    }
    for path, jobs in expected.items():
        symbols = by_path[path].symbols
        assert {symbol.name: symbol.elements for symbol in symbols} == jobs
        lines = by_path[path].content.decode("utf-8").split("\n")
        for symbol in symbols:
            assert symbol.kind is SymbolKind.JOB
            assert lines[symbol.first_line - 1] == f"  {symbol.name}:"


