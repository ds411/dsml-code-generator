# trace: PRD-CICD-010, PRD-CICD-016, PRD-CICD-017, PRD-CICD-018, PRD-CICD-021
def test_deploy_job_applies_then_migrates_then_rolls_out(workflows: dict[str, str]) -> None:
    for job_id, path in DEPLOY_JOBS.items():
        job = _jobs(workflows[path])[job_id]
        environment = job_id.removeprefix("deploy-")
        assert _steps(job) == [
            "Check out the repository",
            "Set up OpenTofu",
            "Get AWS credentials for the deploy role",
            "Initialize OpenTofu",
            f"Apply the infrastructure of {environment}",
            "Run the migrations of orderApi",
            "Roll out orderApi",
            "Write the deployment in the job summary",
        ]
        account = {"dev": "222222222222", "staging": "333333333333"}.get(environment)
        role = names.deploy_role("order-service", environment)
        assert f':role/{role}"\n' in job
        if account is not None:
            assert f'role-to-assume: "arn:aws:iam::{account}:role/{role}"\n' in job
        assert f'working-directory: "infra/envs/{environment}"\n' in job
        assert f'tofu_version: "{pinned_version("opentofu")}"\n' in job
        assert (
            "tofu apply -input=false -auto-approve -no-color\n"
            '          -var "model_commit=$MODEL_COMMIT"\n'
            '          -var "order_api_image_digest=$ORDER_API_IMAGE_DIGEST"\n'
        ) in job
        assert "aws ecs run-task" in job
        assert "aws ecs wait tasks-stopped" in job
        assert 'if [ "$exit_code" != "0" ]; then' in job
        assert "aws ecs update-service" in job
        assert "aws ecs wait services-stable" in job
        assert "rolled back" in job
        assert f'TASK_FAMILY: "order-service-{environment}-api-service"\n' in job
        assert job.index("aws ecs run-task") < job.index("aws ecs update-service")


