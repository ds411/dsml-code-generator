def _step(job: str, name: str) -> str:
    """Give the text of the step with a name, without the next steps."""
    start = job.index(f"      - name: {name}\n")
    end = job.find("\n      - name: ", start + 1)
    return job[start:] if end < 0 else job[start:end]


