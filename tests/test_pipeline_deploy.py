def test_deploy_jobs_skip_environments_that_the_model_does_not_have(ir: Ir) -> None:
    builds = build_jobs(ir, CONFIGURATION)
    assert [build.job for build in builds] == ["build-order-api"]
    jobs = deploy_jobs(
        ir, CONFIGURATION, ("qa", "prod"), builds, "x.{job}.{output}", "c", ("first",)
    )
    assert [job.job for job in jobs] == ["deploy-prod"]
    assert jobs[0].needs == ("first",)
    assert [digest.expression for digest in jobs[0].digests] == [
        "x.build-order-api.ORDER_API_IMAGE_DIGEST"
    ]
    assert [(rollout.address, rollout.migrates) for rollout in jobs[0].rollouts] == [
        ("api_service", True)
    ]
