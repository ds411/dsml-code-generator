def _jobs(text: str) -> dict[str, str]:
    """Give the text of each job, by job ID."""
    lines = text.split("\n")
    symbols = job_symbols(text, lambda job: ("x",))
    return {
        symbol.name: "\n".join(lines[symbol.first_line - 1 : symbol.last_line])
        for symbol in symbols
    }


def _steps(job: str) -> list[str]:
    """Give the names of the steps of a job, in their order."""
    return [name.strip('"') for name in re.findall(r"^      - name: (.+)$", job, re.MULTILINE)]


def _needs(job: str) -> list[str]:
    """Give the jobs in the list `needs` of a job."""
    match = re.search(r"^    needs:\n((?:      - .+\n)+)", job + "\n", re.MULTILINE)
    return [] if match is None else re.findall(r"- (.+)", match.group(1))


