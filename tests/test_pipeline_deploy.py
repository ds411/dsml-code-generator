def test_main_workflow_runs_on_a_push_to_main_and_builds_before_dev(
    workflows: dict[str, str],
) -> None:
    text = workflows[MAIN_PATH]
    assert text.startswith(
        "# Generated by dsml 0. Do not edit.\n"
        "# Elements: OrderService::apiService, OrderService::dev, OrderService::orderApi, "
        "OrderService::tooling\n\n"
        'name: Main\n\non:\n  push:\n    branches:\n      - "main"\n\npermissions: {}\n'
    )
    jobs = _jobs(text)
    assert tuple(jobs) == MAIN_JOBS
    assert _needs(jobs["deploy-dev"]) == ["build-order-api"]
    assert "${{ needs.build-order-api.outputs.ORDER_API_IMAGE_DIGEST }}" in jobs["deploy-dev"]
    assert "MODEL_COMMIT: ${{ github.sha }}\n" in jobs["deploy-dev"]


